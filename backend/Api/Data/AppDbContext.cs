using Api.Entities;
using Microsoft.EntityFrameworkCore;

namespace Api.Data;

public class AppDbContext(DbContextOptions<AppDbContext> options) : DbContext(options)
{
    public DbSet<Room> Rooms => Set<Room>();
    public DbSet<Member> Members => Set<Member>();
    public DbSet<Booking> Bookings => Set<Booking>();

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        modelBuilder.Entity<Room>(room =>
        {
            room.Property(r => r.Name).HasMaxLength(Room.NameMaxLength);
            room.Property(r => r.Equipment).HasMaxLength(Room.EquipmentMaxLength);

            // Room names are unique (MySQL's default collation compares case-insensitively).
            room.HasIndex(r => r.Name).IsUnique();

            // Safety net: the API validates first, the database refuses a non-positive capacity anyway.
            room.ToTable(table => table.HasCheckConstraint("CK_Rooms_Capacity_Positive", "`Capacity` > 0"));
        });

        modelBuilder.Entity<Member>(member =>
        {
            member.Property(m => m.Name).HasMaxLength(Member.NameMaxLength);
            member.Property(m => m.Email).HasMaxLength(Member.EmailMaxLength);

            // The subscription type is stored as text ("Standard", "Premium"): readable directly in SQL.
            member.Property(m => m.SubscriptionType).HasConversion<string>().HasMaxLength(20);

            member.HasIndex(m => m.Email).IsUnique();
        });

        modelBuilder.Entity<Booking>(booking =>
        {
            booking.Property(b => b.Purpose).HasMaxLength(Booking.PurposeMaxLength);
            booking.Property(b => b.Status).HasConversion<string>().HasMaxLength(20);

            // The creation date is generated by MySQL, not by application code.
            booking.Property(b => b.CreatedAt).HasDefaultValueSql("CURRENT_TIMESTAMP(6)");

            // Rooms and members are never deleted when they have a history: deactivate them instead.
            booking.HasOne(b => b.Room).WithMany(r => r.Bookings)
                .HasForeignKey(b => b.RoomId).OnDelete(DeleteBehavior.Restrict);
            booking.HasOne(b => b.Member).WithMany(m => m.Bookings)
                .HasForeignKey(b => b.MemberId).OnDelete(DeleteBehavior.Restrict);

            // Safety net: the API validates first, the database refuses an inverted interval anyway.
            booking.ToTable(table => table.HasCheckConstraint("CK_Bookings_EndAt_After_StartAt", "`EndAt` > `StartAt`"));

            // Indexes for the queries of the planning (all of them filter on Status = Confirmed).
            // Schedule without a room filter: confirmed bookings sorted by start, filtered by date.
            booking.HasIndex(b => new { b.Status, b.StartAt });

            // Schedule filtered by room, overlap check, "busy right now". Also serves as the RoomId foreign key index.
            booking.HasIndex(b => new { b.RoomId, b.Status, b.StartAt });

            // Quota of a Standard member (upcoming confirmed bookings). Also serves as the MemberId foreign key index.
            booking.HasIndex(b => new { b.MemberId, b.Status, b.StartAt });
        });
    }
}
